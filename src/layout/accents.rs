//! Accents typed in two keys: a "dead" key that types nothing by itself,
//! then the letter it goes on. `´` then `e` is `é`.
//!
//! The layout says which keys are dead (their key symbols are the
//! `dead_*` ones); what an accent and a letter make together is Unicode's
//! own composition, written out here as a table so that no library has to
//! be asked. Generated from Python's `unicodedata`: every Latin letter that
//! has a one-character form with each accent.

/// A dead key's accent: the mark that combines, and the character typed
/// when the key is followed by a space, or by a letter the accent doesn't
/// go on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct Accent {
    pub(crate) mark: char,
    pub(crate) alone: char,
}

/// The accent of the dead key whose key symbol is `sym`.
pub(crate) fn accent(sym: u32) -> Option<Accent> {
    let (mark, alone) = match sym {
        0xfe50 => ('\u{0300}', '\u{0060}'),
        0xfe51 => ('\u{0301}', '\u{00b4}'),
        0xfe52 => ('\u{0302}', '\u{005e}'),
        0xfe53 => ('\u{0303}', '\u{007e}'),
        0xfe54 => ('\u{0304}', '\u{00af}'),
        0xfe55 => ('\u{0306}', '\u{02d8}'),
        0xfe56 => ('\u{0307}', '\u{02d9}'),
        0xfe57 => ('\u{0308}', '\u{00a8}'),
        0xfe58 => ('\u{030a}', '\u{00b0}'),
        0xfe59 => ('\u{030b}', '\u{02dd}'),
        0xfe5a => ('\u{030c}', '\u{02c7}'),
        0xfe5b => ('\u{0327}', '\u{00b8}'),
        0xfe5c => ('\u{0328}', '\u{02db}'),
        _ => return None,
    };
    Some(Accent { mark, alone })
}

/// What `accent` and then `letter` type: the accented letter where there
/// is one; the accent by itself for a space; else the accent and then the
/// letter, as two characters, which is what a typewriter would have done.
pub(crate) fn composed(accent: Accent, letter: char) -> String {
    if letter == ' ' {
        return accent.alone.to_string();
    }
    let found = TABLE
        .iter()
        .find(|(mark, base, _)| *mark == accent.mark && *base == letter);
    match found {
        Some((_, _, whole)) => whole.to_string(),
        None => format!("{}{letter}", accent.alone),
    }
}

