#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_accent_goes_on_the_letter_after_it() {
        let acute = accent(0xfe51).unwrap();
        assert_eq!(composed(acute, 'e'), "\u{00e9}");
        assert_eq!(composed(acute, 'E'), "\u{00c9}");
        let caron = accent(0xfe5a).unwrap();
        assert_eq!(composed(caron, 's'), "\u{0161}");
        let diaeresis = accent(0xfe57).unwrap();
        assert_eq!(composed(diaeresis, 'u'), "\u{00fc}");
    }

    #[test]
    fn an_accent_before_a_space_is_typed_by_itself() {
        let circumflex = accent(0xfe52).unwrap();
        assert_eq!(composed(circumflex, ' '), "^");
    }

    #[test]
    fn an_accent_that_does_not_go_on_a_letter_is_typed_before_it() {
        let cedilla = accent(0xfe5b).unwrap();
        assert_eq!(composed(cedilla, 'x'), "\u{00b8}x");
    }

    #[test]
    fn only_dead_keys_have_accents() {
        assert_eq!(accent(0x0061), None);
        assert!(accent(0xfe50).is_some());
    }
}
